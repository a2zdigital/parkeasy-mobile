// The app's display name has one source: app_identity.json.
//
//     dart run tool/app_identity.dart          write the name everywhere it is needed
//     dart run tool/app_identity.dart --check  fail if anything is out of step, or
//                                              if the name is typed anywhere in lib/ or test/
//
// To rename the app: edit app_identity.json, run this without --check, commit.

import 'dart:convert';
import 'dart:io';

const _dartFile = 'lib/core/config/app_identity.dart';
const _androidFile = 'android/app/src/main/res/values/strings.xml';
const _iosFile = 'ios/Flutter/AppIdentity.xcconfig';

void main(List<String> arguments) {
  final identity =
      jsonDecode(File('app_identity.json').readAsStringSync())
          as Map<String, dynamic>;
  final name = (identity['displayName'] as String).trim();
  if (name.isEmpty) {
    _fail(['app_identity.json: displayName is empty.']);
  }

  final targets = <String, String>{
    _dartFile:
        '// Generated by tool/app_identity.dart from app_identity.json. Do not edit.\n'
        '\n'
        '/// The name shown to users. Never type the name anywhere else.\n'
        "const String appDisplayName = '${name.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}';\n",
    _androidFile:
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by tool/app_identity.dart from app_identity.json. Do not edit. -->\n'
        '<resources>\n'
        '    <string name="app_name">${_xml(name)}</string>\n'
        '</resources>\n',
    _iosFile:
        '// Generated by tool/app_identity.dart from app_identity.json. Do not edit.\n'
        'APP_DISPLAY_NAME=$name\n',
  };

  if (!arguments.contains('--check')) {
    targets.forEach((path, content) {
      File(path)
        ..createSync(recursive: true)
        ..writeAsStringSync(content);
      stdout.writeln('wrote $path');
    });
    return;
  }

  final problems = <String>[];

  targets.forEach((path, content) {
    final file = File(path);
    if (!file.existsSync() || file.readAsStringSync() != content) {
      problems.add('$path is out of step with app_identity.json.');
    }
  });

  // The name must not be typed in app code or tests. Compare without case
  // and without spaces, so spaced and lower-case spellings are caught too.
  final needle = name.toLowerCase().replaceAll(RegExp(r'\s+'), '');
  for (final root in ['lib', 'test']) {
    final directory = Directory(root);
    if (!directory.existsSync()) continue;
    for (final entity in directory.listSync(recursive: true)) {
      if (entity is! File) continue;
      final path = entity.path.replaceAll(r'\', '/');
      if (path == _dartFile) continue;
      if (!RegExp(r'\.(dart|arb|json|yaml)$').hasMatch(path)) continue;
      final lines = entity.readAsLinesSync();
      for (var i = 0; i < lines.length; i++) {
        if (lines[i]
            .toLowerCase()
            .replaceAll(RegExp(r'\s+'), '')
            .contains(needle)) {
          problems.add(
            '$path:${i + 1} contains the app name. Use appDisplayName.',
          );
        }
      }
    }
  }

  if (problems.isNotEmpty) {
    _fail([...problems, '', 'Fix: dart run tool/app_identity.dart']);
  }
  stdout.writeln('App name has a single source.');
}

String _xml(String value) => value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll("'", r"\'")
    .replaceAll('"', r'\"');

Never _fail(List<String> lines) {
  lines.forEach(stderr.writeln);
  exit(1);
}
